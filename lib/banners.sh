    wild)     show_banner_wild ;;
    cyber)    show_banner_cyber ;;
    glitch)   show_banner_glitch ;;
    retro)    show_banner_retro ;;
    3d)       show_banner_3d ;;
    rainbow)  show_banner_rainbow ;;
    fire)     show_banner_fire ;;
